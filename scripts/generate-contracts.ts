import { readFile, writeFile } from "node:fs/promises";
for (const name of ["AgentVault", "VaultFactory", "MockUSD"]) {
  const artifact = JSON.parse(
    await readFile(`contracts/out/${name}.sol/${name}.json`, "utf8"),
  );
  const runtime =
    name === "AgentVault"
      ? `export const agentVaultRuntime = '${artifact.deployedBytecode.object}' as const;\nexport const agentVaultImmutableRanges = ${JSON.stringify(Object.values(artifact.deployedBytecode.immutableReferences).flat())} as const;\n`
      : "";
  await writeFile(
    `packages/shared/src/generated/${name}.ts`,
    `// Generated by pnpm contracts:build. Do not edit.\nexport const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(artifact.abi)} as const;\nexport const ${name[0].toLowerCase() + name.slice(1)}Bytecode = '${artifact.bytecode.object}' as const;\n${runtime}`,
  );
}
